
score = 50
print("Initial score (=):", score)

score += 1
print("After += 1:", score)

score -= 1
print("After -= 1:", score)

score *= 1
print("After *= 1:", score)

score /= 1
print("After /= 1:", score)

score //= 1
print("After //= 1:", score)

score %= 1
print("After %= 1:", score)

score **= 1
print("After **= 1:", score)


