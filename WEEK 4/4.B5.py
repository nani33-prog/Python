Tuple = (5,1,5,5,1,1,5,112,5,6,8,3)
n=len(Tuple)
print("Original Tuple",Tuple)
print("First half of Tuple:",Tuple[:(n//2)])
print("Second half of Tuple:",Tuple[(n//2):])


#OUTPUT
#Original Tuple (5, 1, 5, 5, 1, 1, 5, 112, 5, 6, 8, 3)
#First half of Tuple: (5, 1, 5, 5, 1, 1)
#Second half of Tuple: (5, 112, 5, 6, 8, 3)
