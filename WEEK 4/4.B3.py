OriginalLIST = [2,4,'dd','s']
Tuple=tuple(OriginalLIST)
print("Original List",OriginalLIST)
print("List to tuple \n",Tuple)
print(type(Tuple))
OriginalTuple=(3,5,'dd',55)
LIST=list(OriginalTuple)
print("Original Tuple",OriginalTuple)
print("Tuple to list \n",LIST)
print(type(LIST))

#OUTPUT
#Original List [2, 4, 'dd', 's']
#List to tuple 
# (2, 4, 'dd', 's')
#<class 'tuple'>
#Original Tuple (3, 5, 'dd', 55)
#Tuple to list 
# [3, 5, 'dd', 55]
#<class 'list'>
